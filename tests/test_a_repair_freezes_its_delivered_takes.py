"""INCIDENT 2026-10-19 11:18 PDT: the owner's repair of Jekyll HEL ep01 (a redo of step 09, repair clock
open) queued ALL 28 takes for re-render.  Package P03 (b83eac4, D15) had changed the words every take is
built with -- the UNLETTERED sentence lost "cheque", night takes lost "low sun" -- so `take_currency` read
every delivered take "not current to its card" and `make_room` displaced each one to attempts/.

The rule now: inside an owner's repair window of a DELIVERED episode whose redone steps are the takes' own
step or later, a take whose bytes are the bytes the manifest delivered, or the bytes its own dq record
measured, is current for the render pass.  Words regenerated by newer prompt code never make it stale;
only a take the repair itself replaces renders.  A normal run keeps today's rule exactly.

Replayed on ep01's real records (tests/fixtures/ep01_replay/repair_rerun/): T00's delivered graph, the
graph the aborted run wrote at 11:18 (only the seed and those words differ), T00.dq.json, the delivered
manifest.json and the window the killed run left.  The restored T00.mp4 hashes to 56da138b (sha-verified
2026-10-19); a stand-in file carries that hash here.  No GPU, no ComfyUI, no network."""
from __future__ import annotations

import json
import shutil
from pathlib import Path
from types import SimpleNamespace

import pytest

from studio import repair_clock
from studio import take_currency as tc

FIX = Path(__file__).parent / "fixtures" / "ep01_replay" / "repair_rerun"
DELIVERED_SHA8 = "56da138b"
"""T00.mp4 as step 12 delivered it: manifest.json and T00.dq.json both name these bytes."""


def graph_prompt(name: str) -> str:
    return tc.prompt_of(json.loads((FIX / name).read_text(encoding="utf-8")))


NEW_WORDS = graph_prompt("T00.graph_1118.json")
"""What the code at 0ee5e95 builds for T00's card: the aborted run's own graph."""


@pytest.fixture
def ep01(tmp_path, monkeypatch):
    """ep01's home: T00 with its delivered graph and dq record, the delivered manifest; the stand-in
    bytes hash to 56da138b, any other file to ffffffff."""
    home = tmp_path / "book" / "episodes" / "ep01"
    room = home / "takes" / "r2v"
    room.mkdir(parents=True)
    (room / "T00.mp4").write_bytes(b"restored T00")
    shutil.copy(FIX / "T00.graph.json", room / "T00.graph.json")
    shutil.copy(FIX / "T00.dq.json", room / "T00.dq.json")
    shutil.copy(FIX / "manifest.json", home / "manifest.json")
    monkeypatch.setattr(tc, "sha8_of", lambda p: DELIVERED_SHA8 if Path(p).read_bytes() == b"restored T00"
                        else "ffffffff")
    return SimpleNamespace(home=home, take=room / "T00.mp4", canvas=tc.recorded_canvas(room / "T00.mp4"))


def in_repair(home, steps=("09",)) -> None:
    """The window the killed run left (its own repair.json), or one for other steps."""
    if tuple(steps) == ("09",):
        shutil.copy(FIX / "repair.json", Path(home) / repair_clock.WINDOW)
    else:
        repair_clock.open_window(home, {s: 1 for s in steps}, 1_000.0)


# ---- a normal run: today's rule, exactly -------------------------------------------------

def test_only_the_words_and_the_seed_differ_between_the_two_graphs():
    old, new = (json.loads((FIX / n).read_text(encoding="utf-8")) for n in ("T00.graph.json", "T00.graph_1118.json"))
    differ = {i for k in old if old[k] != new[k] for i in old[k]["inputs"] if old[k]["inputs"][i] != new[k]["inputs"][i]}
    assert differ == {"prompt", "noise_seed"} and set(old) == set(new)
    assert "cheque" in graph_prompt("T00.graph.json") and "cheque" not in NEW_WORDS


def test_a_normal_run_reads_the_reworded_t00_stale(ep01):
    assert not tc.is_current(NEW_WORDS, ep01.take, canvas=ep01.canvas)
    assert not tc.held(NEW_WORDS, ep01.take, ep01.home, canvas=ep01.canvas)
    assert tc.held(graph_prompt("T00.graph.json"), ep01.take, ep01.home, canvas=ep01.canvas)


def test_a_normal_run_freezes_nothing(ep01):
    assert tc.frozen(ep01.take, ep01.home) is None


# ---- inside the owner's repair ------------------------------------------------------------

def test_inside_the_repair_the_delivered_t00_is_frozen(ep01):
    in_repair(ep01.home)
    assert tc.frozen(ep01.take, ep01.home) == "delivered"
    assert tc.held(NEW_WORDS, ep01.take, ep01.home, canvas=ep01.canvas)


def test_bytes_only_the_dq_record_names_are_frozen_as_measured(ep01):
    in_repair(ep01.home)
    manifest = json.loads((ep01.home / "manifest.json").read_text(encoding="utf-8"))
    manifest["inputs"] = [r for r in manifest["inputs"] if not r["path"].endswith("takes/r2v/T00.mp4")]
    (ep01.home / "manifest.json").write_text(json.dumps(manifest), encoding="utf-8")
    assert tc.frozen(ep01.take, ep01.home) == "measured"


def test_bytes_no_record_names_render(ep01):
    in_repair(ep01.home)
    ep01.take.write_bytes(b"a draw nobody measured")
    assert tc.frozen(ep01.take, ep01.home) is None
    assert not tc.held(NEW_WORDS, ep01.take, ep01.home, canvas=ep01.canvas)


def test_an_undelivered_episode_never_freezes(ep01):
    in_repair(ep01.home)
    (ep01.home / "manifest.json").unlink()
    assert tc.frozen(ep01.take, ep01.home) is None


def test_a_repair_of_an_earlier_step_freezes_nothing(ep01):
    in_repair(ep01.home, steps=("07",))
    assert tc.frozen(ep01.take, ep01.home) is None


def test_a_missing_take_is_never_frozen(ep01):
    in_repair(ep01.home)
    ep01.take.unlink()
    assert tc.frozen(ep01.take, ep01.home) is None


# ---- the two readers of currency: step 09's done() and takes_r2v's render pass ------------

def card() -> dict:
    return {"index": 0, "shots": [0], "prompt": NEW_WORDS}


def test_step_09_names_t00_stale_in_a_normal_run_and_none_in_the_repair(ep01, monkeypatch):
    from scripts.episode import step_09_shoot as s09
    room = ep01.home / "takes" / "r2v"
    (room / "prompts.json").write_text(json.dumps([card()]), encoding="utf-8")
    monkeypatch.setattr(s09, "card_pictures", lambda c, book, number: [])
    monkeypatch.setattr(s09, "episode_canvas", lambda ctx: ep01.canvas)
    ctx = SimpleNamespace(home=ep01.home, book_dir=ep01.home.parents[1], number=1)
    assert s09.stale_takes(ctx) == [0]
    in_repair(ep01.home)
    assert s09.stale_takes(ctx) == []


def test_the_render_pass_skips_t00_only_inside_the_repair(ep01, monkeypatch):
    from scripts.episode import takes_r2v
    monkeypatch.setattr(takes_r2v, "card_pictures", lambda c, book, number: [])
    monkeypatch.setattr(takes_r2v, "W", ep01.canvas[0])
    monkeypatch.setattr(takes_r2v, "H", ep01.canvas[1])
    book, records = ep01.home.parents[1], {0: {"index": 0, "shots": [0]}}
    current = lambda: takes_r2v.current_to(card(), ep01.take, book, 1)  # noqa: E731
    assert takes_r2v.wants_render(card(), ep01.take, records, None, current)
    in_repair(ep01.home)
    assert not takes_r2v.wants_render(card(), ep01.take, records, None, current)
